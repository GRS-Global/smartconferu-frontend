// Generates frontend/src/mocks/parity-conferences.ts from the prototype's OWN conference data (read-only).
// The prototype source is never modified: this script reads src/author-journey.jsx, evaluates just the
// conference-generation snippets, and writes a typed fixture file for the Next.js mock layer.
// Run:  node gen-parity-fixtures.mjs        (output is deterministic: no clock, no random)
import fs from "node:fs";
import path from "node:path";

const SRC = path.resolve("../../src/author-journey.jsx");
const lines = fs.readFileSync(SRC, "utf8").split("\n");
const find = (re, from = 0) => { const i = lines.findIndex((l, k) => k >= from && re.test(l)); if (i < 0) throw new Error("not found " + re); return i; };
const block = (startRe, endRe, excl = false) => { const s = find(startRe); const e = find(endRe, s); return lines.slice(s, excl ? e : e + 1).join("\n"); };

const worldCountries = block(/^const WORLD_COUNTRIES = \[/, /^\];/);
const names = block(/^const EXTRA_CONFERENCE_NAMES = \[/, /^\];/);
const cycles = block(/^const ROLE_COMBO_CYCLE = \[/, /^const CONFERENCE_COUNTRY_CYCLE/);
const gen = block(/^const EXTRA_CONFERENCES = /, /^\}\);/);
const roles = block(/^const MY_ROLES = \[/, /^\]\.map/, true).replace(/logoUrl: \w+,\s*/g, "").replace(/\s*\.\.\.EXTRA_CONFERENCES,/, "");

const code = `
${worldCountries}
const COUNTRIES = [...WORLD_COUNTRIES.map(([name]) => name), "Other"];
${names}
${cycles}
${gen}
${roles.replace(/^const MY_ROLES = \[/, "const MY_BASE = [")}];
return [...MY_BASE, ...EXTRA_CONFERENCES];
`;
const all = new Function(code)();
// Archived/active is a function of "today"; the QA harness freezes the clock at FROZEN_NOW, so we derive it from that.
const FROZEN_NOW = "2026-11-03";
const out = all.map((c, i) => ({
  id: c.id, number: i + 1, acronym: c.acronym, name: c.name, roles: c.roles, pinned: !!c.pinned,
  status: c.pinned ? "active" : (c.endDate < FROZEN_NOW ? "archived" : "active"),
  startDate: c.startDate, endDate: c.endDate, city: c.city || "", country: c.country,
}));
const ts = `/* GENERATED by frontend/qa/gen-parity-fixtures.mjs from the prototype's MY_ROLES / EXTRA_CONFERENCES. Do not edit by hand.
   Only used when NEXT_PUBLIC_MOCK_FIXTURES=parity (visual QA). Status is computed for the frozen QA date ${FROZEN_NOW}. */
export const PARITY_CONFERENCES = ${JSON.stringify(out, null, 2)} as const;
`;
fs.writeFileSync(path.resolve("../src/mocks/parity-conferences.ts"), ts);
console.log(`wrote ${out.length} conferences; first: ${out[0].id}, last: ${out.at(-1).id}; archived: ${out.filter((c) => c.status === "archived").length}`);
