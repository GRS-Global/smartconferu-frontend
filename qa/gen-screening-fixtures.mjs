// Phase 3B: turns out/screening-initial.json (what the prototype's Initial Check page shows, see scrape-screening.mjs) into a Next.js
// MOCK-ONLY fixture: src/mocks/parity-screening.ts. Used only when NEXT_PUBLIC_MOCK_SCREENING=parity (a separate QA instance), so the
// regression instance and every other page keep their data. Usage: node gen-screening-fixtures.mjs
import fs from "node:fs";
const rows = JSON.parse(fs.readFileSync("out/screening-initial.json", "utf8"));
const DATE = /[A-Z][a-z]{2} \d{1,2}, \d{4}/;
const KEY = { "No Decision": "pending", Passed: "passed", Hold: "hold", Revision: "revision", Reject: "reject" };
const decisionOf = (r) => r.decision || KEY[(r.decisionText.match(/^(No Decision|Passed|Hold|Revision|Reject)/) || [])[1]] || "pending";

const plag = new Map();
for (const r of JSON.parse(fs.readFileSync("out/screening-plag.json", "utf8"))) if (!plag.has(r.id)) plag.set(r.id, r); // newest version first
const byId = new Map();
for (const r of rows) { if (!byId.has(r.id)) byId.set(r.id, []); byId.get(r.id).push(r); } // latest row first, then older versions
const papers = [], files = {};
let n = 0;
for (const [id, list] of byId) {
  n += 1;
  const versions = list.length;
  const dbId = `parity-${id}`;
  const screening = {}, vf = [];
  list.forEach((r, i) => {
    const v = versions - i; // list[0] is the newest
    const uploaded = (r.submitted.match(DATE) || [""])[0];
    const sent = (r.email.match(/Sent · ([A-Z][a-z]{2} \d{1,2}, \d{4})/) || [])[1] || null;
    const due = (r.email.match(/(?:Overdue · |Due )([A-Z][a-z]{2} \d{1,2}, \d{4})/) || [])[1];
    const decision = decisionOf(r);
    const rec = { check: { decision, editable: r.editable, english: r.english, column: r.column, pages: r.pages, ...(sent ? { emailedAt: sent } : {}), edited: { editable: true, english: true, column: true, pages: true } } };
    if (decision === "revision" && (due || sent)) rec.correction = { reasons: [], deadline: due, emailedAt: sent };
    if (i === 0) {
      // plagiarism stage of the newest version (from the prototype's Plagiarism Check page)
      const pr = plag.get(id);
      if (pr) {
        const psent = (pr.email.match(/Sent · ([A-Z][a-z]{2} \d{1,2}, \d{4})/) || [])[1] || null;
        const pdue = (pr.email.match(/(?:Overdue · |Due )([A-Z][a-z]{2} \d{1,2}, \d{4})/) || [])[1];
        if (pr.files.length) rec.report = { similarity: null, ai: null, files: pr.files, file: pr.files[0] };
        if (pr.locked) rec.outcome = { kind: "clear", reasons: [], note: "" };
        else if (pr.decision && pr.decision !== "pending") rec.outcome = { kind: pr.decision, reasons: [], note: "", ...(pdue ? { deadline: pdue } : {}), ...(psent ? { emailedAt: psent } : {}) };
      }
    }
    screening[String(v)] = rec;
    const missing = (r.autoNote.match(/Missing: (.*)$/) || [])[1];
    vf.push({ n: v, name: `${id}_paper_v${v}.pdf`, uploadedAt: uploaded, auto: { status: "done", pages: Number(r.pages) || 0, editable: r.editable, english: r.english, column: r.column, ...(missing ? { missing: missing.split(", ").map((s) => s.replace(" ", "_")) } : {}) }, storagePath: null });
  });
  vf.sort((a, b) => a.n - b.n);
  files[dbId] = vf;
  const head = list[0];
  papers.push({
    id, dbId, conferenceId: "demo-dsai-2027", title: head.title, track: "", presentationType: "Paper Presentation", authors: [{ name: "Author", email: "author@example.org", affiliation: "", country: "India", corresponding: true, hasAccount: true }], keywords: [],
    submittedAt: vf[vf.length - 1].uploadedAt, lastUpdate: vf[vf.length - 1].uploadedAt, withdrawn: false, withdrawnAt: "", withdrawnBy: "author", outcome: "no_decision", decisionTypeId: null, notifiedOutcome: null,
    reviewersAssigned: head.locked ? 3 : 0, reviewsReceived: 0, averageScore: null, versions, screening,
  });
}
const out = `/* GENERATED by qa/gen-screening-fixtures.mjs from the prototype's Initial Check page. Mock mode only (NEXT_PUBLIC_MOCK_SCREENING=parity); do not edit. */
import type { ChairPaper, ScreeningFile } from "@/types/chair";
export const SCREENING_PAPERS: ChairPaper[] = ${JSON.stringify(papers)};
export const SCREENING_FILES: Record<string, ScreeningFile[]> = ${JSON.stringify(files)};
`;
fs.writeFileSync("../src/mocks/parity-screening.ts", out);
console.log("papers", papers.length, "rows", rows.length, "locked", papers.filter((p) => p.reviewersAssigned).length);
