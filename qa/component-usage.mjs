// Builds the import graph of ../src and maps every shared component (src/components/**) to the routes that
// depend on it, directly or through feature code. Output: out/component-usage.json and ../design-system/REGRESSION.md
// Usage: node component-usage.mjs            (map)
//        node component-usage.mjs --pages ui/field.tsx   (print the QA page ids affected by changing that file)
import fs from "node:fs";
import path from "node:path";
import { PAGES } from "./pages.mjs";

const SRC = path.resolve("../src");
const files = [];
(function walk(d) { for (const e of fs.readdirSync(d, { withFileTypes: true })) { const p = path.join(d, e.name); e.isDirectory() ? walk(p) : /\.(tsx?|css)$/.test(e.name) && files.push(p); } })(SRC);
const rel = (f) => path.relative(SRC, f).replaceAll("\\", "/");

const resolveImport = (from, spec) => {
  let base;
  if (spec.startsWith("@/")) base = path.join(SRC, spec.slice(2));
  else if (spec.startsWith(".")) base = path.resolve(path.dirname(from), spec);
  else return null;
  for (const c of [base, base + ".ts", base + ".tsx", base + ".css", path.join(base, "index.ts"), path.join(base, "index.tsx")]) if (fs.existsSync(c) && fs.statSync(c).isFile()) return c;
  return null;
};
const deps = new Map(); // file -> Set(files it imports)
for (const f of files) {
  const text = fs.readFileSync(f, "utf8");
  const set = new Set();
  for (const m of text.matchAll(/(?:import|export)\s[^;]*?from\s+["']([^"']+)["']|import\(\s*["']([^"']+)["']\s*\)|import\s+["']([^"']+)["']/g)) {
    const r = resolveImport(f, m[1] || m[2] || m[3]); if (r) set.add(r);
  }
  deps.set(f, set);
}
const reverse = new Map();
for (const [f, set] of deps) for (const d of set) (reverse.get(d) || reverse.set(d, new Set()).get(d)).add(f);

const dependentsOf = (file) => { const seen = new Set(), q = [file]; while (q.length) { const x = q.pop(); for (const p of reverse.get(x) || []) if (!seen.has(p)) { seen.add(p); q.push(p); } } return seen; };
const routeOf = (f) => "/" + rel(f).replace(/^app\//, "").replace(/\/page\.tsx$/, "").replace(/\((?:authed|app|workspace)\)\/?/g, "").replace(/\/$/, "");

// Which QA page ids does a Next route correspond to? (dynamic segments -> the fixture value used in pages.mjs)
const norm = (r) => r.replace(/\[[^\]]+\]/g, "*");
const qaFor = (route) => PAGES.filter((p) => { const a = norm(route).split("/").filter(Boolean), b = p.next.split("?")[0].split("/").filter(Boolean); return a.length === b.length && a.every((s, i) => s === "*" || s === b[i]); }).map((p) => p.id);

const pagesOf = (file) => [...dependentsOf(file)].filter((f) => /\/app\/.*page\.tsx$/.test(f.replaceAll("\\", "/")) || /app\/page\.tsx$/.test(f.replaceAll("\\", "/"))).map(routeOf);

if (process.argv.includes("--pages")) {
  const target = path.join(SRC, "components", process.argv[process.argv.indexOf("--pages") + 1].replace(/^components\//, ""));
  const routes = pagesOf(target);
  const ids = [...new Set(routes.flatMap(qaFor))];
  console.log(JSON.stringify({ file: rel(target), routes, qaPageIds: ids, routesWithoutQaPage: routes.filter((r) => !qaFor(r).length) }, null, 2));
  process.exit(0);
}

const comps = files.filter((f) => rel(f).startsWith("components/") && /\.tsx$/.test(f));
const usage = comps.map((f) => { const routes = [...new Set(pagesOf(f))].sort(); return { component: rel(f), importedByFiles: (reverse.get(f)?.size || 0), routes: routes.length, routeList: routes, qaPageIds: [...new Set(routes.flatMap(qaFor))], routesWithoutQaPage: routes.filter((r) => !qaFor(r).length) }; }).sort((a, b) => b.routes - a.routes);
// global styles reach every page
const globalsCss = ["app/globals.css", "styles/tokens.css"].filter((f) => fs.existsSync(path.join(SRC, f)));
fs.mkdirSync("out", { recursive: true });
fs.writeFileSync("out/component-usage.json", JSON.stringify({ generatedAt: new Date().toISOString(), globalsCss, usage }, null, 2));

const allRoutes = files.filter((f) => /app\/.*page\.tsx$/.test(f.replaceAll("\\", "/"))).map(routeOf);
const md = ["# Shared-component regression map", "", "Generated by `qa/component-usage.mjs` from the real import graph (do not edit by hand). Changing any file below means re-running `node run-compare.mjs --page <ids>` and `node run-audit.mjs --page <ids>` for the listed QA page ids **and** fixing any regression before reporting done. `app/globals.css` and `styles/tokens.css` affect **every** page: run the full suite.", "",
  `Routes in the app: ${allRoutes.length}. Routes with no entry in \`qa/pages.mjs\` are listed per component (coverage gap).`, "",
  "| Component | Routes depending on it | QA page ids to re-run | Routes with no QA coverage |", "|---|---|---|---|",
  ...usage.map((u) => `| ${u.component} | ${u.routes} | ${u.qaPageIds.join(", ") || "-"} | ${u.routesWithoutQaPage.length ? u.routesWithoutQaPage.join(", ") : "-"} |`), "",
  "Quick check for one file: `node component-usage.mjs --pages ui/field.tsx`", ""];
fs.writeFileSync("../design-system/REGRESSION.md", md.join("\n"));
console.log(`components: ${usage.length}, app routes: ${allRoutes.length}`);
for (const u of usage.slice(0, 12)) console.log(String(u.routes).padStart(3), u.component, "-> qa pages:", u.qaPageIds.length, "| uncovered routes:", u.routesWithoutQaPage.length);
