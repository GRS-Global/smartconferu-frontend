import { NEXT, VIEWPORTS } from "./pages.mjs";
import { launch, newContext, openStable } from "./lib.mjs";
import { makePdf } from "./qa-pdf.mjs";
const b = await launch(); const ctx = await newContext(b, VIEWPORTS[0], true);
await ctx.route("**/__qa-paper.pdf", (r) => r.fulfill({ status: 200, contentType: "application/pdf", body: makePdf(3) }));
const pg = await ctx.newPage(); const r = {};
await openStable(pg, NEXT + "/submissions/DSAI-6/chair/review/add"); await pg.waitForTimeout(5000);
r.toolbar = await pg.evaluate(() => ["Previous page", "Next page", "Zoom out", "Zoom in", "Search the paper", "Page number"].map((l) => !!document.querySelector(`[aria-label='${l}']`)));
r.pages = await pg.evaluate(() => document.querySelectorAll("[data-page]").length);
r.ofTotal = await pg.evaluate(() => (document.body.innerText.match(/of (\d+|–)/) || [null])[0]);
r.zoomBefore = await pg.evaluate(() => (document.body.innerText.match(/(\d+)%/) || [null])[1]);
await pg.getByRole("button", { name: "Zoom in" }).click(); await pg.waitForTimeout(500);
r.zoomAfter = await pg.evaluate(() => [...document.querySelectorAll("button")].map((x) => x.textContent.trim()).find((t) => /^\d+%$/.test(t)));
await pg.getByRole("button", { name: "Next page" }).click(); await pg.waitForTimeout(900);
r.pageNow = await pg.getByLabel("Page number").inputValue();
await pg.getByRole("button", { name: "Search the paper" }).click(); await pg.getByLabel("Search the paper").fill("reinforcement"); await pg.keyboard.press("Enter"); await pg.waitForTimeout(1500);
r.hits = await pg.evaluate(() => (document.body.innerText.match(/\d+ of \d+(?= )/g) || []).slice(-1)[0] ?? document.body.innerText.match(/No results/)?.[0]);
r.marked = await pg.locator(".pv-hit").count();
await pg.screenshot({ path: "out/det/pdf.png" });
console.log(JSON.stringify(r)); await b.close();
