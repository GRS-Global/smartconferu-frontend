// Chair Peer Review slice 2: turns out/peer-review-proto.json (what the prototype's Peer Review pages show, see scrape-peer-review.mjs) into a Next.js
// MOCK-ONLY fixture: src/mocks/parity-peerreview.ts (committee, each paper's reviewers, decided papers, the conference's decision types). Used only
// with NEXT_PUBLIC_MOCK_SCREENING=parity, on top of the 498 screening papers. Usage: node gen-peer-fixtures.mjs
import fs from "node:fs";
const o = JSON.parse(fs.readFileSync("out/peer-review-proto.json", "utf8"));
const MONTHS = { Jan: 1, Feb: 2, Mar: 3, Apr: 4, May: 5, Jun: 6, Jul: 7, Aug: 8, Sep: 9, Oct: 10, Nov: 11, Dec: 12 };
const iso = (s) => { const m = (s || "").match(/([A-Z][a-z]{2}) (\d{1,2}), (\d{4})/); return m ? `${m[3]}-${String(MONTHS[m[1]]).padStart(2, "0")}-${String(m[2]).padStart(2, "0")}` : ""; };
const hex = (rgb) => { const m = (rgb || "").match(/\d+/g); return m ? "#" + m.slice(0, 3).map((x) => Number(x).toString(16).padStart(2, "0")).join("") : "#64748b"; };
const strip = (t) => t.replace(/^[A-Z]{1,3}\s+/, "").trim();
const OUTCOME = { "Paper Upload Pending": "upload_pending", "No Decision": "no_decision", "Plagiarism clear": "plagiarism_clear", Revision: "revise", Waitlist: "waitlist", Accept: "accept", Registered: "registered", Reject: "reject" };

const poolList = o.pool.map((p, i) => ({ memberId: `pm-${i}`, userId: p.invited ? null : `pu-${i}`, name: p.name.replace(/\s+Invited.*$/, "").trim(), email: p.email, tracks: [], status: p.invited ? "invited" : "active", invitedAt: "Sep 01, 2026" }));
const types = o.decisionTypes.map((t) => ({ id: `dt-${t.label.toLowerCase().replace(/\W+/g, "-")}`, label: t.label, color: hex(t.color), outcome: OUTCOME[t.label], description: "" }));
const typeByLabel = Object.fromEntries(types.map((t) => [t.label, t]));

const CONF = { High: "high", Medium: "medium", Low: "low" };
const lineOf = (r, i) => (r.scoreCol[i] || "").match(/^(\d(?:\.\d)?)\/5\s*(.*)$/);
const scoreOf = (r, i) => (lineOf(r, i) ? Number(lineOf(r, i)[1]) : 4);
const recOf = (r, i) => (lineOf(r, i)?.[2] || "").trim();
const similarity = {};
const board = {}, patch = {};
for (const r of o.rows) {
  const dbId = `parity-${r.id}`;
  const live = r.reviewers.filter((x) => !x.struck), dead = r.reviewers.filter((x) => x.struck);
  const reviewers = live.map((x, i) => {
    const name = strip(x.text);
    const word = (r.reviewCol[i] || "").trim();
    const due = iso(r.dueCol[i] || "");
    const pool = poolList.find((p) => p.name === name);
    const submitted = word === "Submitted";
    return { assignmentId: `pa-${r.id}-${i}`, reviewerId: pool?.userId ?? pool?.memberId ?? `pu-x-${name}`, name, email: pool?.email ?? "", response: word === "Not accepted yet" || word === "Invite pending" ? "pending" : "accepted", assignedAt: "Oct 02, 2026", due, byChair: false, awaitingInvite: word === "Invite pending",
      review: submitted ? { id: `pr-${r.id}-${i}`, score: scoreOf(r, i), confidence: CONF[r.conf] ?? "high", commentsToAuthor: "", commentsToChair: "", shared: false, submittedAt: "Oct 20, 2026", answers: recOf(r, i) ? { "f-decision": recOf(r, i) } : {} } : null };
  });
  board[dbId] = { reviewers, declined: dead.map((x) => ({ name: strip(x.text), reason: "Declined", at: "Oct 05, 2026" })) };
  const scored = reviewers.filter((x) => x.review);
  const p = { reviewersAssigned: reviewers.length, reviewsReceived: scored.length, averageScore: scored.length ? Math.round((scored.reduce((a, x) => a + x.review.score, 0) / scored.length) * 10) / 10 : null };
  if (r.decision && r.decision.value !== "pending") { const t = typeByLabel[r.decision.text]; if (t) { p.outcome = t.outcome; p.decisionTypeId = t.id; p.notifiedOutcome = t.outcome; } }
  patch[dbId] = p;
  const sim = (r.plag || "").match(/^(\d+(?:\.\d+)?)%/); if (sim) similarity[dbId] = Number(sim[1]);
}
const out = `/* GENERATED by qa/gen-peer-fixtures.mjs from the prototype's Peer Review pages. Mock mode only (NEXT_PUBLIC_MOCK_SCREENING=parity); do not edit. */
import type { ChairPaper, DecisionType, ReviewBoard, ReviewerPool } from "@/types/chair";
export const PEER_POOL: ReviewerPool = { reviewers: ${JSON.stringify(poolList)}, tracks: [] };
export const PEER_BOARD: ReviewBoard = { target: 2, deadline: "2026-12-05", papers: ${JSON.stringify(board)} };
export const PEER_PATCH: Record<string, Partial<ChairPaper>> = ${JSON.stringify(patch)};
export const PEER_SIMILARITY: Record<string, number> = ${JSON.stringify(similarity)};
export const PEER_DECISION_TYPES: DecisionType[] = ${JSON.stringify(types)};
`;
fs.writeFileSync("../src/mocks/parity-peerreview.ts", out);
console.log("pool", poolList.length, "types", types.length, "papers", Object.keys(board).length, "with reviewers", Object.values(patch).filter((p) => p.reviewersAssigned).length, "decided", Object.values(patch).filter((p) => p.outcome).length);
